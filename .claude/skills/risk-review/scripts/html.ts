// Small helpers for the HTML the Review guide's scripts write.

/** Escapes text for HTML, in content and in a quoted attribute. */
export const esc = (text: string) =>
  text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
